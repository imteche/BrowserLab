#!/usr/bin/env node
/* Generates index.html (script tags for every registered file) and
 * dist/browserlab.html (single self-contained file, fonts inlined). */
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');

function js(dir, filter) {
  const d = path.join(ROOT, dir);
  if (!fs.existsSync(d)) return [];
  return fs.readdirSync(d).filter(f => f.endsWith('.js') && (!filter || filter(f))).sort().map(f => dir + '/' + f);
}

/* orchestration/graph.json -> js/graph-data.js */
const gj = path.join(ROOT, 'orchestration/graph.json');
if (fs.existsSync(gj)) {
  fs.writeFileSync(path.join(ROOT, 'js/graph-data.js'),
    '/* generated by tools/build.js from orchestration/graph.json */\n(function (LAB) { LAB.graph = ' +
    fs.readFileSync(gj, 'utf8').trim() + '; })(typeof window !== \'undefined\' ? window.LAB : globalThis.LAB);\n');
}

const scripts = [
  'js/core.js', 'js/scenes.js',
  ...js('references', f => f.startsWith('sources-')),
  ...js('references', f => !f.startsWith('sources-')),
  'js/overlays.js',
  ...js('methods'),
  ...js('verification/results'),
  ...(fs.existsSync(path.join(ROOT, 'js/graph-data.js')) ? ['js/graph-data.js'] : [])
];

const tpl = fs.readFileSync(path.join(__dirname, 'index.template.html'), 'utf8');
const tags = scripts.map(s => '<script src="' + s + '"></script>').join('\n');
fs.writeFileSync(path.join(ROOT, 'index.html'), tpl.replace('<!--SCRIPTS-->', tags));

/* ---- single-file bundle ---- */
function dataUri(file) {
  return 'data:font/woff2;base64,' + fs.readFileSync(file).toString('base64');
}
function inlineCss(file) {
  let css = fs.readFileSync(path.join(ROOT, file), 'utf8');
  const dir = path.dirname(path.join(ROOT, file));
  return css.replace(/url\((['"]?)([^'")]+\.woff2)\1\)/g, (m, q, u) => {
    const f = path.resolve(dir, u);
    return fs.existsSync(f) ? 'url(' + dataUri(f) + ')' : 'url(about:blank)';
  }).replace(/,\s*url\([^)]+\.(woff|ttf)\)\s*format\(['"](woff|truetype)['"]\)/g, '');
}
let html = tpl;
html = html.replace('<link rel="stylesheet" href="vendor/katex/katex.min.css">', '<style>' + inlineCss('vendor/katex/katex.min.css') + '</style>');
html = html.replace('<link rel="stylesheet" href="css/lab.css">', '<style>' + inlineCss('css/lab.css') + '</style>');
const inl = f => '<script>/* ' + f + ' */\n' + fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/<\/script/gi, '<\\/script') + '\n</script>';
html = html.replace('<script src="vendor/katex/katex.min.js"></script>', inl('vendor/katex/katex.min.js'));
html = html.replace('<!--SCRIPTS-->', scripts.map(inl).join('\n'));
html = html.replace('<script src="js/ui.js"></script>', inl('js/ui.js'));
fs.mkdirSync(path.join(ROOT, 'dist'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'dist/browserlab.html'), html);
/* artifact variant: page content only (host supplies doctype/head/body skeleton) */
const head = html.slice(html.indexOf('<head>') + 6, html.indexOf('</head>')).replace(/<meta charset[^>]*>|<meta name="viewport"[^>]*>/g, '');
const body = html.slice(html.indexOf('<body>') + 6, html.lastIndexOf('</body>'));
fs.writeFileSync(path.join(ROOT, 'dist/browserlab.artifact.html'), head.trim() + '\n' + body.trim() + '\n');
console.log('index.html: ' + scripts.length + ' scripts; dist/browserlab.html: ' + (html.length / 1024).toFixed(0) + ' KiB');
