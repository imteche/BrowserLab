#!/usr/bin/env node
/* Generates SOURCES.md and VERIFICATION.md from the registries (single source of truth). */
'use strict';
const fs = require('fs');
const path = require('path');
const H = require('./harness.js');
const LAB = H.load();
const ROOT = H.ROOT;

const md = s => String(s == null ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

/* ---------- SOURCES.md ---------- */
const used = {};
const use = (id, by) => { (used[id] = used[id] || new Set()).add(by); };
for (const m of Object.values(LAB.methods)) {
  (m.sources || []).forEach(s => use(s, 'method ' + m.id));
  (m.equations || []).forEach(e => use(e.source, 'method ' + m.id + ' (' + e.label + ', ' + (e.location || 'no location') + ')'));
}
for (const r of Object.values(LAB.references)) if (!r.id.endsWith('-overlay')) use(r.source, 'reference ' + r.id + (r.location ? ' (' + r.location + ')' : ''));

let s = '# Source catalogue\n\nGenerated by `tools/catalogue.js` from `references/sources-*.js`. Do not edit by hand.\n\n';
s += 'Access modes: **full-text** (the agent read the cited section), **secondary-copy** (values or formulas read from an open copy such as a permissively licensed repository that reproduces the original), **search-snippet** (only a search-result excerpt was readable). `verified` is true only when the agent read the cited location itself.\n\n';
s += 'Network note: this lab was built from a container where arxiv.org, publisher sites and most institutional hosts were unreachable; GitHub, PyPI and npm were reachable. That is why most primary papers are cited through open secondary copies and carry `verified: false`.\n\n';
const ids = Object.keys(LAB.sources).sort();
const counts = ids.reduce((a, id) => { const k = LAB.sources[id].access + (LAB.sources[id].verified ? ' (verified)' : ''); a[k] = (a[k] || 0) + 1; return a; }, {});
s += '| Access | Count |\n|---|---|\n' + Object.entries(counts).map(([k, v]) => `| ${k} | ${v} |`).join('\n') + '\n\n';
s += '| id | Source | URL | Access | Verified | Used by |\n|---|---|---|---|---|---|\n';
for (const id of ids) {
  const x = LAB.sources[id];
  s += `| \`${id}\` | ${md(x.authors)} (${md(x.year)}). *${md(x.title)}*. ${md(x.venue)}${x.doi ? ' doi:' + md(x.doi) : ''}${x.accessNote ? '<br><sub>' + md(x.accessNote) + '</sub>' : ''} | <${x.url}> | ${md(x.access)} | ${x.verified ? 'yes' : 'no'} | ${used[id] ? [...used[id]].map(md).join('<br>') : '—'} |\n`;
}
fs.writeFileSync(path.join(ROOT, 'SOURCES.md'), s);

/* ---------- VERIFICATION.md ---------- */
const recs = Object.values(LAB.verification).sort((a, b) => a.id.localeCompare(b.id));
const tally = { matched: 0, flagged: 0, incomplete: 0 };
recs.forEach(r => tally[r.status]++);
let v = '# Verification summary\n\nGenerated by `tools/catalogue.js` from `verification/results/*.js`. Each record was written by a reviewer agent independent of the builder of that method; every number is reproducible with the matching script in `verification/checks/`.\n\n';
v += `**${tally.matched} matched · ${tally.flagged} flagged · ${tally.incomplete} incomplete** across ${Object.keys(LAB.methods).length} methods.\n\n`;
const exps = [];
Object.values(LAB.scenes).forEach(sc => (sc.experiments || []).forEach(e => exps.push({ scene: sc.id, id: e.id })));
v += '| Method | ' + exps.map(e => e.id).join(' | ') + ' |\n|---|' + exps.map(() => '---').join('|') + '|\n';
for (const m of Object.values(LAB.methods)) {
  v += `| ${md(m.name)} | ` + exps.map(e => {
    if (!m.scenes[e.scene]) return '·';
    const r = LAB.verification[m.id + '@' + e.id];
    return r ? r.status.toUpperCase() : 'not reviewed';
  }).join(' | ') + ' |\n';
}
v += '\n';
for (const st of ['flagged', 'incomplete', 'matched']) {
  const list = recs.filter(r => r.status === st);
  if (!list.length) continue;
  v += `## ${st[0].toUpperCase() + st.slice(1)} (${list.length})\n\n`;
  for (const r of list) {
    v += `### \`${r.id}\`\n\n**Claim.** ${r.claim}\n\n`;
    if (r.conditions) v += '**Conditions.** ' + Object.entries(r.conditions).map(([k, x]) => `${k} = ${typeof x === 'object' ? JSON.stringify(x) : x}`).join('; ') + '\n\n';
    if (r.gaps && r.gaps.length) v += '| Quantity | Gap | Tolerance | Pass |\n|---|---|---|---|\n' + r.gaps.map(g => `| ${md(g.quantity)} | ${md(typeof g.value === 'number' ? Number(g.value.toPrecision(4)) : g.value)} ${md(g.unit || '')} | ${md(g.tolerance)} | ${g.pass ? 'yes' : '**no**'} |`).join('\n') + '\n\n';
    const fails = (r.checks || []).filter(c => c.status === 'fail');
    if (fails.length) v += '**Failed checks.**\n' + fails.map(c => `- ${c.name}: ${c.detail}`).join('\n') + '\n\n';
    if (r.missing && r.missing.length) v += '**Missing for full verification.**\n' + r.missing.map(x => `- ${x}`).join('\n') + '\n\n';
    if (r.history && r.history.length > 1) v += '**Loop history.** ' + r.history.map(h => `round ${h.round}: ${h.status}${h.reason ? ' — ' + h.reason : ''}`).join(' → ') + '\n\n';
    v += `Report: [verification/reports/${r.id}.md](verification/reports/${encodeURIComponent(r.id)}.md) · Check: \`node verification/checks/${r.id}.check.js\`\n\n`;
  }
}
fs.writeFileSync(path.join(ROOT, 'VERIFICATION.md'), v);
console.log(`SOURCES.md: ${ids.length} sources; VERIFICATION.md: ${recs.length} records`, tally);
if (LAB.problems.length) { console.log('registry problems:', LAB.problems); process.exitCode = 1; }
